#!/usr/bin/env bash
# Navigation benchmark only. Never calls the MATLAB/closed-loop launcher.
set -euo pipefail
NAV_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$NAV_ROOT"

usage() {
  cat <<'EOF'
Usage: shell/run_navigation_tests.sh {check|smoke|run|analyze} [options]
       shell/run_navigation_tests.sh --check-only [options]
check: check/install missing pinned dependencies, checkpoint inference and renderer.
       --check-only forbids installation (also accepted without an action).
smoke: foreground only; --duration SECONDS defaults to 2 (simulation time).
run:   full benchmark; --resume requires an existing --output directory.
analyze: analyze an existing --output; no GPU/checkpoint/renderer probe.
Options:
  --config FILE                default configs/navigation_tests.yaml
  --output DIR                 run/smoke: autogenerated by main.navigation_tests
  --device {cuda,cpu}           config default cuda; record hardware for timing
  --renderer {blender,cpu}      config default blender; cpu is synthetic smoke only
  --render-device {OPTIX,CUDA,CPU}  config default OPTIX
  --render-python PATH         optional isolated Python 3.11 bpy environment
  --suite {main,gimbal,stress,all}  omitted: use main module/config default all
  --seeds-per-cell N            optional positive integer override
  --workers N                   smoke/run: positive integer; config default 2
                                independent record groups run in spawned processes
  --render-threads N            smoke/run: positive integer per worker; config default 4
  --torch-threads N             smoke/run: positive integer per worker; config default 2
  --source PATH                actual recorded run, fixed inputs, main suite only
  --trajectory PATH            actual recorded body/deck trajectory to rerender
  --background [--session NAME] run only, in tmux; smoke always foreground
Paths are relative to the repository root. Source and trajectory are exclusive.
Environment: PYTHON_BIN, RENDER_PYTHON, LANDING_DOWNLOAD_PROFILE=china,
LANDING_TORCH_INDEX and existing download_mirrors.sh overrides.
No MATLAB installation, model edits, automatic shutdown or accuracy claim.
EOF
}
fail() { printf '%s\n' "$*" >&2; exit 2; }
# POSIX single quoting also keeps logs valid UTF-8 on macOS Bash 3.2, whose
# printf %q can escape only part of a multibyte character in some locales.
quote_arg() {
  local value="$1" quote="'" escaped="'\\''"
  printf "'%s'" "${value//$quote/$escaped}"
}
quote_args() {
  local argument
  for argument in "$@"; do quote_arg "$argument"; printf ' '; done
}

NAV_MODE=check
if [[ $# -gt 0 && "$1" != -* ]]; then NAV_MODE="$1"; shift; fi
case "$NAV_MODE" in check|smoke|run|analyze) ;; *) usage >&2; exit 2 ;; esac
NAV_CONFIG=configs/navigation_tests.yaml
NAV_OUTPUT="" NAV_DEVICE="" NAV_RENDERER="" NAV_RENDER_DEVICE=""
NAV_RENDER_PYTHON="${RENDER_PYTHON:-}" NAV_SUITE="" NAV_SEEDS="" NAV_DURATION=2
NAV_WORKERS="" NAV_RENDER_THREADS="" NAV_TORCH_THREADS=""
NAV_SOURCE="" NAV_TRAJECTORY="" NAV_SESSION=""
NAV_BACKGROUND=0 NAV_RESUME=0 NAV_CHECK_ONLY=0 NAV_DURATION_SET=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    -h|--help) usage; exit 0 ;;
    --background) NAV_BACKGROUND=1; shift; continue ;;
    --resume) NAV_RESUME=1; shift; continue ;;
    --check-only) NAV_CHECK_ONLY=1; shift; continue ;;
  esac
  NAV_OPTION="${1%%=*}"
  case "$NAV_OPTION" in
    --config|--output|--device|--renderer|--render-device|--render-python|--suite|--seeds-per-cell|--workers|--render-threads|--torch-threads|--duration|--source|--trajectory|--session) ;;
    *) fail "Unknown option: $1 (see --help)" ;;
  esac
  if [[ "$1" == *=* ]]; then
    NAV_VALUE="${1#*=}"; shift
  else
    [[ $# -ge 2 && "$2" != --* ]] || fail "Missing value for $1"
    NAV_VALUE="$2"; shift 2
  fi
  [[ -n "$NAV_VALUE" ]] || fail "Empty value for $NAV_OPTION"
  case "$NAV_OPTION" in
    --config) NAV_CONFIG="$NAV_VALUE" ;;
    --output) NAV_OUTPUT="$NAV_VALUE" ;;
    --device) NAV_DEVICE="$NAV_VALUE" ;;
    --renderer) NAV_RENDERER="$NAV_VALUE" ;;
    --render-device) NAV_RENDER_DEVICE="$NAV_VALUE" ;;
    --render-python) NAV_RENDER_PYTHON="$NAV_VALUE" ;;
    --suite) NAV_SUITE="$NAV_VALUE" ;;
    --seeds-per-cell) NAV_SEEDS="$NAV_VALUE" ;;
    --workers) NAV_WORKERS="$NAV_VALUE" ;;
    --render-threads) NAV_RENDER_THREADS="$NAV_VALUE" ;;
    --torch-threads) NAV_TORCH_THREADS="$NAV_VALUE" ;;
    --duration) NAV_DURATION="$NAV_VALUE"; NAV_DURATION_SET=1 ;;
    --source) NAV_SOURCE="$NAV_VALUE" ;;
    --trajectory) NAV_TRAJECTORY="$NAV_VALUE" ;;
    --session) NAV_SESSION="$NAV_VALUE" ;;
  esac
done
[[ -z "$NAV_DEVICE" || "$NAV_DEVICE" == cuda || "$NAV_DEVICE" == cpu ]] || fail 'Choose --device cuda or cpu'
[[ -z "$NAV_RENDERER" || "$NAV_RENDERER" == blender || "$NAV_RENDERER" == cpu ]] || fail 'Choose --renderer blender or cpu'
case "$NAV_RENDER_DEVICE" in ''|OPTIX|CUDA|CPU) ;; *) fail 'Choose --render-device OPTIX, CUDA or CPU' ;; esac
case "$NAV_SUITE" in ''|main|gimbal|stress|all) ;; *) fail 'Choose --suite main, gimbal, stress or all' ;; esac
[[ -z "$NAV_SEEDS" || "$NAV_SEEDS" =~ ^[1-9][0-9]*$ ]] || fail '--seeds-per-cell must be a positive integer'
[[ -z "$NAV_WORKERS" || "$NAV_WORKERS" =~ ^[1-9][0-9]*$ ]] || fail '--workers must be a positive integer'
[[ -z "$NAV_RENDER_THREADS" || "$NAV_RENDER_THREADS" =~ ^[1-9][0-9]*$ ]] || fail '--render-threads must be a positive integer'
[[ -z "$NAV_TORCH_THREADS" || "$NAV_TORCH_THREADS" =~ ^[1-9][0-9]*$ ]] || fail '--torch-threads must be a positive integer'
if [[ ( -n "$NAV_WORKERS" || -n "$NAV_RENDER_THREADS" || -n "$NAV_TORCH_THREADS" ) && "$NAV_MODE" != smoke && "$NAV_MODE" != run ]]; then
  fail '--workers, --render-threads and --torch-threads are allowed only for smoke/run'
fi
[[ "$NAV_DURATION_SET" == 0 || "$NAV_MODE" == smoke ]] || fail '--duration is allowed only for smoke'
[[ "$NAV_DURATION" =~ ^[0-9]+([.][0-9]+)?$ && "$NAV_DURATION" =~ [1-9] ]] || fail '--duration must be positive finite seconds'
[[ "$NAV_BACKGROUND" == 0 || "$NAV_MODE" == run ]] || fail '--background is allowed only for run; smoke stays foreground'
[[ -z "$NAV_SESSION" || "$NAV_BACKGROUND" == 1 ]] || fail '--session requires --background'
[[ -z "$NAV_SESSION" || "$NAV_SESSION" =~ ^[a-zA-Z0-9_-]+$ ]] || fail 'Session name must contain only letters, digits, underscores and hyphens'
[[ "$NAV_CHECK_ONLY" == 0 || "$NAV_MODE" == check ]] || fail '--check-only is a standalone check action; it never launches a benchmark'
[[ "$NAV_RESUME" == 0 || "$NAV_MODE" == run ]] || fail '--resume is allowed only for run'
if [[ "$NAV_RESUME" == 1 || "$NAV_MODE" == analyze ]]; then
  [[ -n "$NAV_OUTPUT" && -d "$NAV_OUTPUT" ]] || fail '--resume/analyze requires --output pointing to an existing directory'
fi
[[ -z "$NAV_SOURCE" || -z "$NAV_TRAJECTORY" ]] || fail '--source and --trajectory are mutually exclusive'
if [[ -n "$NAV_SOURCE" ]]; then
  [[ -z "$NAV_SUITE" || "$NAV_SUITE" == main ]] || fail '--source is fixed-input replay and permits only --suite main'
  NAV_SUITE=main
fi
if [[ "$NAV_MODE" == check && ( -n "$NAV_OUTPUT" || -n "$NAV_SEEDS" || -n "$NAV_SUITE" && -z "$NAV_SOURCE" ) ]]; then
  fail 'check accepts environment/source options; suite, seeds and output belong to benchmark actions'
fi
if [[ "$NAV_MODE" == analyze && ( -n "$NAV_SOURCE" || -n "$NAV_TRAJECTORY" || -n "$NAV_SEEDS" || -n "$NAV_SUITE" ) ]]; then
  fail 'analyze reads the existing output; source, trajectory, suite and seeds belong to smoke/run'
fi

source "$NAV_ROOT/shell/download_mirrors.sh"
export OMP_NUM_THREADS="${OMP_NUM_THREADS:-4}" OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1
export PYTHONUNBUFFERED=1 PYTHONDONTWRITEBYTECODE=1 MPLBACKEND=Agg
export PIP_DEFAULT_TIMEOUT="${PIP_DEFAULT_TIMEOUT:-120}" PIP_RETRIES="${PIP_RETRIES:-5}"
export UV_HTTP_TIMEOUT="${UV_HTTP_TIMEOUT:-120}" UV_HTTP_RETRIES="${UV_HTTP_RETRIES:-5}"
NAV_BOOTSTRAP=""
for NAV_CANDIDATE in "${PYTHON_BIN:-}" "$NAV_ROOT/.venv/bin/python" python3 python python3.12 python3.11; do
  if [[ -n "$NAV_CANDIDATE" ]] && command -v "$NAV_CANDIDATE" >/dev/null 2>&1 &&
      "$NAV_CANDIDATE" -c 'import sys; sys.exit(sys.version_info < (3, 10))' >/dev/null 2>&1; then
    NAV_BOOTSTRAP="$NAV_CANDIDATE"; break
  fi
done
[[ -n "$NAV_BOOTSTRAP" ]] || fail 'Python >=3.10 is required to bootstrap (Ubuntu 22.04: install python3 python3-venv)'

NAV_LOG_DIR="$NAV_ROOT/outputs/logs/navigation_tests/$(date +%Y%m%d_%H%M%S)_${NAV_MODE}_$$"
mkdir -p "$NAV_LOG_DIR"
trap 'NAV_STATUS=$?; printf "%s\n" "$NAV_STATUS" > "$NAV_LOG_DIR/exit.code"' EXIT
printf 'Console log: %s\n' "$NAV_LOG_DIR/console.log"
NAV_ENV_ARGS=(--config "$NAV_CONFIG" --report-dir "$NAV_LOG_DIR")
if [[ -n "$NAV_DEVICE" ]]; then NAV_ENV_ARGS+=(--device "$NAV_DEVICE"); fi
if [[ -n "$NAV_RENDERER" ]]; then NAV_ENV_ARGS+=(--renderer "$NAV_RENDERER"); fi
if [[ -n "$NAV_RENDER_DEVICE" ]]; then NAV_ENV_ARGS+=(--render-device "$NAV_RENDER_DEVICE"); fi
if [[ "$NAV_CHECK_ONLY" == 1 ]]; then NAV_ENV_ARGS+=(--check-only); fi
if [[ "$NAV_BACKGROUND" == 1 ]]; then NAV_ENV_ARGS+=(--with-tmux); fi
if [[ "$NAV_MODE" == analyze ]]; then NAV_ENV_ARGS+=(--analysis-only); fi
if [[ -n "$NAV_RENDER_PYTHON" ]]; then NAV_ENV_ARGS+=(--render-python "$NAV_RENDER_PYTHON"); fi
if [[ -n "$NAV_SOURCE" ]]; then NAV_ENV_ARGS+=(--source "$NAV_SOURCE"); fi
if [[ -n "$NAV_TRAJECTORY" ]]; then NAV_ENV_ARGS+=(--trajectory "$NAV_TRAJECTORY"); fi
"$NAV_BOOTSTRAP" "$NAV_ROOT/shell/navigation_test_dependencies.py" "${NAV_ENV_ARGS[@]}" 2>&1 | tee "$NAV_LOG_DIR/console.log"
IFS= read -r NAV_PYTHON < "$NAV_LOG_DIR/python.txt"
IFS= read -r NAV_RENDER_PYTHON < "$NAV_LOG_DIR/render-python.txt"
IFS= read -r NAV_DEVICE < "$NAV_LOG_DIR/device.txt"
IFS= read -r NAV_RENDERER < "$NAV_LOG_DIR/renderer.txt"
IFS= read -r NAV_RENDER_DEVICE < "$NAV_LOG_DIR/render-device.txt"
if [[ -n "$NAV_RENDER_PYTHON" ]]; then export RENDER_PYTHON="$NAV_RENDER_PYTHON"; else unset RENDER_PYTHON; fi
if [[ "$NAV_MODE" == check ]]; then exit 0; fi

NAV_COMMAND=("$NAV_PYTHON" -u -m main.navigation_tests "$NAV_MODE" --config "$NAV_CONFIG"
             --device "$NAV_DEVICE" --renderer "$NAV_RENDERER" --render-device "$NAV_RENDER_DEVICE")
if [[ -n "$NAV_OUTPUT" ]]; then NAV_COMMAND+=(--output "$NAV_OUTPUT"); fi
if [[ -n "$NAV_SUITE" ]]; then NAV_COMMAND+=(--suite "$NAV_SUITE"); fi
if [[ -n "$NAV_SEEDS" ]]; then NAV_COMMAND+=(--seeds-per-cell "$NAV_SEEDS"); fi
if [[ -n "$NAV_WORKERS" ]]; then NAV_COMMAND+=(--workers "$NAV_WORKERS"); fi
if [[ -n "$NAV_RENDER_THREADS" ]]; then NAV_COMMAND+=(--render-threads "$NAV_RENDER_THREADS"); fi
if [[ -n "$NAV_TORCH_THREADS" ]]; then NAV_COMMAND+=(--torch-threads "$NAV_TORCH_THREADS"); fi
if [[ -n "$NAV_SOURCE" ]]; then NAV_COMMAND+=(--source "$NAV_SOURCE"); fi
if [[ -n "$NAV_TRAJECTORY" ]]; then NAV_COMMAND+=(--trajectory "$NAV_TRAJECTORY"); fi
if [[ -n "$NAV_RENDER_PYTHON" && "$NAV_RENDERER" == blender && -z "$NAV_SOURCE" ]]; then
  NAV_COMMAND+=(--render-python "$NAV_RENDER_PYTHON")
fi
if [[ "$NAV_MODE" == smoke ]]; then NAV_COMMAND+=(--duration "$NAV_DURATION"); fi
if [[ "$NAV_RESUME" == 1 ]]; then NAV_COMMAND+=(--resume); fi
printf 'Command: %s\n' "$(quote_args "${NAV_COMMAND[@]}")" | tee -a "$NAV_LOG_DIR/console.log"

# A Bash script carries argv safely across tmux; never eval user-supplied text.
# Snapshot runtime variables because an existing tmux server can have stale env.
NAV_WORKER="$NAV_LOG_DIR/worker.sh"
{
  printf '#!/usr/bin/env bash\nset -euo pipefail\ncd -- '
  quote_arg "$NAV_ROOT"; printf '\n'
  for NAV_KEY in PATH PYTHONPATH PYTHON_BIN RENDER_PYTHON CUDA_VISIBLE_DEVICES NVIDIA_VISIBLE_DEVICES LD_LIBRARY_PATH LD_PRELOAD OMP_NUM_THREADS OPENBLAS_NUM_THREADS MKL_NUM_THREADS PYTHONUNBUFFERED PYTHONDONTWRITEBYTECODE MPLBACKEND; do
    if [[ "${!NAV_KEY+x}" == x ]]; then
      printf 'export %s=' "$NAV_KEY"; quote_arg "${!NAV_KEY}"; printf '\n'
    else
      printf 'unset %s\n' "$NAV_KEY"
    fi
  done
  printf 'status_file='; quote_arg "$NAV_LOG_DIR/exit.code"; printf '\n'
  printf '%s\n' 'trap '\''status=$?; printf "%s\n" "$status" > "$status_file"'\'' EXIT'
  quote_args "${NAV_COMMAND[@]}"
  printf '2>&1 | tee -a '; quote_arg "$NAV_LOG_DIR/console.log"; printf '\n'
} > "$NAV_WORKER"
if [[ "$NAV_BACKGROUND" == 1 ]]; then
  NAV_SESSION="${NAV_SESSION:-navigation_$(date +%Y%m%d_%H%M%S)_$$}"
  # tmux >=3.2 (Ubuntu 22.04) executes multiple command arguments directly,
  # without parsing paths through its configured login shell.
  tmux new-session -d -s "$NAV_SESSION" -c "$NAV_ROOT" bash "$NAV_WORKER"
  trap - EXIT
  printf 'Started tmux session: %s\nAttach: tmux attach -t %s\nLog: %s\nExit status when finished: %s\n' \
    "$NAV_SESSION" "$NAV_SESSION" "$NAV_LOG_DIR/console.log" "$NAV_LOG_DIR/exit.code"
else
  trap - EXIT
  exec bash "$NAV_WORKER"
fi
