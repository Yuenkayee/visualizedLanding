function used=landing_control_used(s)
% Values actually evaluated inside the supplied guidance during this step.
root=s.live_model; cmd=[root '/' s.config.autonomous_subsystem '/LAND_CMD'];
used=struct('source_timestamp',s.feedback.timestamp,'evaluated_at',s.timestamp, ...
    'cg_relative_ned_m',read([root '/LandingControlCG']), ...
    'valid',logical(read([root '/LandingControlValid'])), ...
    'target_relative_ned_m',read([cmd '/Plus'],2), ...
    'error_ned_m',read([cmd '/Plus']), ...
    'relative_velocity_command_knots',read([cmd '/NavigationValidityGate']), ...
    'gate_valid_input',read([cmd '/NavigationValidityGate'],2), ...
    'ship_feedforward_knots',read([cmd '/Plus1'],2), ...
    'velocity_command_knots',read([cmd '/Plus1']));
assert(norm(used.cg_relative_ned_m-s.feedback.cg_relative_estimate_50hz_ned(:))<1e-8 && ...
    used.valid==logical(s.feedback.cg_signal_valid),'landing:Feedback','Plant consumed stale navigation');
assert(norm(used.error_ned_m-(used.target_relative_ned_m-used.cg_relative_ned_m))<1e-8, ...
    'landing:Feedback','Guidance error sign or reference point mismatch');
assert(abs(used.gate_valid_input-double(used.valid))<1e-12 && ...
    norm(used.velocity_command_knots-used.relative_velocity_command_knots-used.ship_feedforward_knots)<1e-8, ...
    'landing:Feedback','Guidance gate timing or command sum mismatch');
if ~used.valid
    assert(norm(used.relative_velocity_command_knots)<1e-12,'landing:Feedback', ...
        'Invalid navigation commanded closing velocity: source=%g gate=%g relative=%s total=%s', ...
        double(used.valid),used.gate_valid_input,mat2str(used.relative_velocity_command_knots),mat2str(used.velocity_command_knots));
end
end
function value=read(block,input)
r=get_param(block,'RuntimeObject');
assert(~isempty(r),'landing:Feedback','Missing control runtime probe: %s',block);
if nargin==2, value=double(r.InputPort(input).Data); else, value=double(r.OutputPort(1).Data); end
value=value(:);
end
