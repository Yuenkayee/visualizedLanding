function values=landing_conversion_inputs(s)
% Raw inputs to the existing convert System block, including real gimbal
% angles for rendering and measured encoder data for navigation separately.
g=s.config.geometry; e=s.estimate;
if isempty(e)
    e=struct('T_deck_camera',eye(4),'velocity',zeros(3,1),'covariance',eye(6), ...
        'healthy',false,'timestamp',s.timestamp,'angular_velocity_camera',zeros(3,1));
end
m=struct('T_body_camera',g.T_body_camera,'angular_velocity_camera',zeros(3,1), ...
    'covariance',zeros(3),'valid',false,'timestamp',s.timestamp);
if isfield(e,'gimbal') && ~isempty(e.gimbal), m=e.gimbal; end
q=zeros(3,1); if isfield(s,'gimbal_state'), q=s.gimbal_state.angles; end
values=struct('timestamp',s.timestamp,'nav_T_deck_camera',e.T_deck_camera, ...
    'nav_velocity_deck',e.velocity(:),'nav_covariance',e.covariance, ...
    'nav_healthy',double(e.healthy),'nav_timestamp',e.timestamp, ...
    'gimbal_angles_rad',q,'nav_R_body_camera',m.T_body_camera(1:3,1:3), ...
    'nav_gimbal_omega_camera',m.angular_velocity_camera(:),'nav_gimbal_covariance',m.covariance, ...
    'nav_gimbal_valid',double(m.valid),'nav_gimbal_timestamp',m.timestamp, ...
    'nav_angular_velocity_camera',e.angular_velocity_camera(:));
end
