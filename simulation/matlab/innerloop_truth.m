function truth=innerloop_truth(s)
assert(strcmp(s.phase,'read') || strcmp(s.phase,'feedback'), ...
    'landing:Order','Invalid state-read phase');
o=innerloop_evaluate(s);
A=[0 1 0;1 0 0;0 0 -1]; Rdeck=A'*o.T_world_deck(1:3,1:3);
Rbody=Rdeck*o.T_deck_camera(1:3,1:3)*o.T_body_camera_actual(1:3,1:3)';
gear=Rdeck'*o.gear_relative_truth_ned;
offset=s.config.geometry.gear_body(:)-o.T_body_camera_actual(1:3,4);
vgear=o.velocity_deck+Rdeck'*Rbody*cross(s.helicopter_state(10:12),offset) ...
    -cross(diag([1 -1 -1])*s.ship_state(10:12),gear-o.T_deck_camera(1:3,4));
truth=struct('timestamp',s.timestamp,'T_world_deck',o.T_world_deck, ...
    'T_deck_camera',o.T_deck_camera,'velocity_deck',o.velocity_deck', ...
    'T_body_camera',o.T_body_camera_actual,'gear_position_deck',gear', ...
    'gear_velocity_deck',vgear');
end
