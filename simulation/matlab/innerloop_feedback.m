function s=innerloop_feedback(s,e)
assert(strcmp(s.phase,'read'),'landing:Order','Feedback already written; advance before next feedback');
assert(isfield(s,'observed_timestamp') && abs(s.observed_timestamp-s.timestamp)<1e-8, ...
    'landing:Order','Read current sensor truth before writing feedback');
s.estimate=e;
% Reference commands are separate from encoders. Latch at the feedback phase;
% gimbal_step applies the physical response only when the plant advances.
if isfield(e,'gimbal_reference') && isstruct(e.gimbal_reference)
    cmd=e.gimbal_reference; R=cmd.R_deck_camera;
    assert(abs(cmd.timestamp-s.timestamp)<1e-8,'landing:Gimbal','Stale reference command');
    assert(isequal(size(R),[3 3]) && all(isfinite(R(:))) && ...
        norm(R'*R-eye(3),'fro')<1e-6 && abs(det(R)-1)<1e-6, ...
        'landing:Gimbal','Invalid reference rotation');
    s.gimbal_reference=cmd;
end
o=innerloop_evaluate(s);
[s.cg_signal_state,cg_position,cg_velocity,cg_valid,cg_age]=cg_signal_step( ...
    s.cg_signal_state,s.timestamp,o.cg_relative_estimate_ned, ...
    o.navigation_velocity_cg_ned_mps,o.feedback_valid,e.timestamp,s.config.cg_signal_parameters);
s.feedback=struct('timestamp',s.timestamp, ...
    'gear_relative_ned_m',o.gear_relative_estimate_ned, ...
    'distance_m',o.relative_distance_estimate_m, ...
    'covariance_ned',o.relative_covariance_ned,'valid',logical(o.feedback_valid), ...
    'velocity_gear_ned_mps',o.navigation_velocity_gear_ned_mps, ...
    'T_deck_body',o.nav_T_deck_body, ...
    'cg_relative_truth_ned',o.cg_relative_truth_ned, ...
    'cg_relative_estimate_ned',o.cg_relative_estimate_ned, ...
    'navigation_velocity_cg_ned_mps',o.navigation_velocity_cg_ned_mps, ...
    'cg_relative_covariance_ned',o.cg_relative_covariance_ned, ...
    'ship_angular_velocity_deck',diag([1 -1 -1])*s.ship_state(10:12), ...
    'cg_relative_estimate_50hz_ned',cg_position, ...
    'cg_relative_velocity_50hz_ned_mps',cg_velocity, ...
    'cg_signal_valid',logical(cg_valid),'cg_signal_age_s',cg_age);
s.phase='feedback';
end
